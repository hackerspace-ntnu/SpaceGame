// Sits the rider in the saddle.
//
// Drop this next to a MountModule and whoever climbs on stops standing to attention above the
// seat and starts riding. The seat itself is a CLIP: the "Ride" action, a real seated mocap loop
// with the legs opened round the barrel (RideClipGenerator), played on the rider's full-body action
// layer. It replaced a pose built here by rotating bones over the STANDING idle, which read as a
// mannequin folded onto the saddle. On top of the clip this adds what no clip can know: the pelvis
// sits on the saddle's seat and rocks with it (RideSaddle), and the back gives with the mount's
// measured bounce, speed and turns.
//
// "Whoever climbs on" is meant literally: a mount takes a player through MountModule and an NPC
// through NpcPassenger, and both sit in the same saddle. PoseRider/ReleaseRider are the way in for
// anyone who is not a PlayerMovement — the caravan's nomads rode across the desert standing bolt
// upright for no better reason than that this class could only be reached through a mount event.
//
// Deliberately knows nothing about ostriches. Everything it reacts to is measured off the mount's
// own transform, so it works on the ant, the crawler, the horse and anything else that grows a
// MountModule — and, just as importantly, it does not drag Assembly-CSharp into the
// SpaceGame.Creatures.Ostrich asmdef to ask a locomotion component how fast it thinks it is going.
using UnityEngine;
using SpaceGame.Characters;
using SpaceGame.Presentation;

namespace SpaceGame.Agents
{
    // After Unity evaluates the Animator (that happens in PreLateUpdate, ahead of every
    // LateUpdate) so these writes land on top of the clip rather than under it, and before
    // MountModule's order-1000 camera pass.
    [DefaultExecutionOrder(900)]
    [DisallowMultipleComponent]
    public class MountedRiderPose : MonoBehaviour
    {
        [Tooltip("Mount this poses the rider of. Found on this GameObject when empty.")]
        [SerializeField] private MountModule mountModule;

        [Header("Seated Clip")]
        [Tooltip("The full-body loop the rider sits in: a real seated mocap loop with the legs opened " +
                 "round an animal's barrel, generated by Tools/SpaceGame/Animation/Generate Ride Clip " +
                 "(RidePoseProfile) and played by name from the action catalog.")]
        [SerializeField] private string rideActionName = "Ride";

        [Header("Motion Response")]
        [SerializeField] private RiderPoseGains gains = RiderPoseGains.Default;
        [Tooltip("How fast the measured motion catches up. Raw frame-to-frame deltas off a legged " +
                 "mount are far too noisy to drive a spine with.")]
        [SerializeField, Min(0.01f)] private float motionSmooth = 9f;
        [Tooltip("Ignore measured speeds above this, in m/s and degrees/s. A chunk load, a scene " +
                 "migration or a leap landing can move the mount a very long way in one frame, and " +
                 "that is not a stride.")]
        [SerializeField, Min(0f)] private float motionRejectThreshold = 60f;

        [Header("Saddle")]
        [Tooltip("Metres the rider's hip joint sits above the saddle's seat marker " +
                 "(SaddleSocket.RiderSeat). The rider is parented to the mount's ROOT, which does " +
                 "not move when the animal's back does, so without this the saddle heaves and rolls " +
                 "under a rider frozen in place. With a saddle on, the pelvis is put on the seat every " +
                 "frame and the body rides the back. No saddle: the rider stays where seatOffset put them.")]
        [SerializeField] private float hipsAboveSeat = 0.22f;

        [Tooltip("Share of the saddle's pitch and roll the rider's body takes, 0..1. The rider's own " +
                 "balance takes the rest: a rider rocks with the animal, but less than it does.")]
        [SerializeField, Range(0f, 1f)] private float swayFollow = 0.6f;

        [Tooltip("Seconds over which the saddle's resting tilt is learned. Only rocking faster than " +
                 "this sways the rider; a slope or a lowered head is the animal's posture, not a stride.")]
        [SerializeField, Min(0.05f)] private float swayBaselineSeconds = 1.2f;

        [Header("Blend")]
        [Tooltip("Seconds to ease into the pose on mounting and out of it on dismounting. Without " +
                 "it the rider snaps between standing and seated on the frame the mount lands.")]
        [SerializeField, Min(0.01f)] private float blendDuration = 0.25f;

        // Rider references are cached here rather than read back off MountModule, because they have
        // to outlive the dismount: the pose blends OUT over blendDuration, and by then MountModule
        // has already cleared everything it knew about the rider.
        private Animator riderAnimator;
        private Transform riderRoot;
        private CharacterActions riderActions;
        private CharacterAction rideAction;

        private float weight;
        private float targetWeight;

        private Vector3 lastMountPosition;
        private float lastMountYaw;
        private bool hasLastSample;

        private float smoothedVertical;
        private float smoothedForward;
        private float smoothedTurn;

        private SaddleSocket saddleSocket;
        private Quaternion swayBaseline;
        private bool hasSwayBaseline;

        /// <summary>Current blend weight, 0 (animator owns the bones) to 1 (fully seated).</summary>
        public float Weight => weight;

        // The seat on the live saddle, which rides the animal's back bone; null with no saddle on.
        private Transform Seat => saddleSocket != null ? saddleSocket.RiderSeat : null;

        private void Awake()
        {
            saddleSocket = GetComponentInParent<SaddleSocket>();

            if (!mountModule)
                mountModule = GetComponent<MountModule>();

            if (!mountModule)
                Debug.LogWarning($"[MountedRiderPose] No MountModule on {name}; nobody will be posed.", this);

            CharacterActionCatalog catalog = CharacterActionCatalog.Default;
            if (catalog == null || !catalog.TryFind(rideActionName, out rideAction))
                Debug.LogError($"[MountedRiderPose] No action '{rideActionName}' in the action catalog; riders on " +
                               $"{name} will not sit. Run Tools/SpaceGame/Animation/Generate Ride Clip.", this);
        }

        private void OnEnable()
        {
            if (!mountModule)
                return;

            mountModule.Mounted += HandleMounted;
            mountModule.Dismounted += HandleDismounted;

            // Enabled onto an already-ridden mount — a domain reload, or a module toggled back on.
            // The player path is asked of MountModule; any other rider is whoever was in the saddle
            // when this was switched off, which is nobody unless it was switched off mid-ride.
            if (mountModule.IsMounted)
                HandleMounted(mountModule.MountedPlayerMovement);
            else if (riderRoot != null)
                PoseRider(riderRoot);
        }

        private void OnDisable()
        {
            if (mountModule)
            {
                mountModule.Mounted -= HandleMounted;
                mountModule.Dismounted -= HandleDismounted;
            }

            // Release the bones outright rather than blending: there is no LateUpdate coming to
            // finish the blend with, so a partial pose would be frozen onto the rider for good.
            //
            // The rider REFERENCE stays, so switching this back on puts whoever is still in the
            // saddle back into the pose. LateUpdate clears it on an ordinary dismount, so what
            // survives here is only a rider who was aboard when the component went away.
            StandUp();
            weight = 0f;
            targetWeight = 0f;
            riderAnimator = null;
            hasLastSample = false;
        }

        private void HandleMounted(PlayerMovement rider) =>
            PoseRider(mountModule ? mountModule.MountedPlayerTransform : null);

        private void HandleDismounted(PlayerMovement rider) =>
            ReleaseRider(rider ? rider.transform : riderRoot);

        /// <summary>
        /// Sit <paramref name="rider"/> in the saddle, whoever they are.
        ///
        /// <para>
        /// Public because a mount carries two quite different kinds of rider and only one of them
        /// arrives through <see cref="MountModule"/>: a player mounts, and a caravan's NPC is
        /// seated by <see cref="NpcPassenger"/>. Nothing below this line cares which — the pose is
        /// read off the mount's own motion and written through the rider's humanoid avatar — and
        /// the NPC riders spent the whole journey standing to attention above the saddle purely
        /// because there was no way in here that did not go through a PlayerMovement.
        /// </para>
        /// </summary>
        public void PoseRider(Transform rider)
        {
            // A different rider starts from standing rather than inheriting the last one's pose.
            // Without this, a player mounting an animal whose nomad has just been turfed out lands
            // fully seated on the frame they sit down, and the blend that exists to stop exactly
            // that snap never runs.
            if (riderRoot != rider)
                weight = 0f;

            if (riderRoot != rider)
                StandUp();

            riderRoot = rider;
            riderAnimator = riderRoot ? riderRoot.GetComponentInChildren<Animator>(true) : null;
            riderActions = riderRoot ? riderRoot.GetComponentInChildren<CharacterActions>(true) : null;

            // Bones are resolved through the humanoid avatar, so a generic rig has nothing to
            // resolve them against and is left to its animator untouched.
            if (riderAnimator != null && !riderAnimator.isHuman)
            {
                Debug.LogWarning($"[MountedRiderPose] {riderAnimator.name} is not a humanoid rig; " +
                                 "no riding pose will be applied.", this);
                riderAnimator = null;
            }

            targetWeight = riderAnimator != null ? 1f : 0f;
            ResetMotionSamples();
        }

        /// <summary>
        /// Blend <paramref name="rider"/> back out of the pose.
        ///
        /// Ignores anybody else's rider, so a late release from the NPC path cannot cancel the pose
        /// of the player who has just taken the seat off them. References stay put — LateUpdate
        /// keeps posting the decaying pose until it reaches 0.
        /// </summary>
        public void ReleaseRider(Transform rider)
        {
            if (rider != null && riderRoot != rider)
                return;

            targetWeight = 0f;
            StandUp();
        }

        // The seated loop is the rider's own animator state, so it has to be handed back; the
        // bones this writes after the animator need nothing, the animator rewrites them next frame.
        private void StandUp()
        {
            if (riderActions != null)
                riderActions.Stop(rideAction);
        }

        private void ResetMotionSamples()
        {
            hasLastSample = false;
            hasSwayBaseline = false;
            smoothedVertical = 0f;
            smoothedForward = 0f;
            smoothedTurn = 0f;
        }

        private void LateUpdate()
        {
            float deltaTime = Time.deltaTime;

            weight = Mathf.MoveTowards(weight, targetWeight, deltaTime / blendDuration);

            if (weight <= 0f)
            {
                if (targetWeight <= 0f)
                {
                    riderAnimator = null;
                    riderRoot = null;
                    hasLastSample = false;
                }
                return;
            }

            if (riderAnimator == null || riderRoot == null)
                return;

            // Re-asserted every frame while seated (a running loop asked again is a no-op), so a
            // full-body one-shot that took the layer — a flinch — gives the saddle back afterwards.
            // Only the body's animator writer starts it; the player's network animator carries the
            // state to everyone watching, and every machine plays an NPC's itself.
            if (targetWeight > 0f && riderActions != null)
                riderActions.Play(rideAction);

            SampleMountMotion(deltaTime);
            RideSaddle(deltaTime);
            ApplyMotion(RiderPoseMath.SpineOffset(smoothedVertical, smoothedForward, smoothedTurn, gains));
        }

        /// <summary>
        /// Put the rider's pelvis on the saddle's seat and rock the body with the saddle.
        ///
        /// <para>
        /// The rider hangs off the mount's root — netcode allows no other parent — and a creature's
        /// root glides along the NavMesh while its back heaves, rolls and pitches through every
        /// stride. The saddle rides that back bone; the rider did not, and sat frozen above a saddle
        /// moving underneath them. Moving the HIPS bone, after the animator, rather than the rider's
        /// transform keeps this pure presentation: every machine derives it from the animal's own
        /// animation, nothing accumulates frame to frame (the animator rewrites the hips), and the
        /// replicated rider transform and its first-person camera are left exactly where seating put them.
        /// </para>
        /// </summary>
        private void RideSaddle(float deltaTime)
        {
            Transform seat = Seat;
            Transform hips = riderAnimator.GetBoneTransform(HumanBodyBones.Hips);
            if (seat == null || hips == null)
                return;

            // The saddle's tilt relative to the mount, measured against its own slowly learned rest
            // so only the rocking of the stride comes through.
            Quaternion tilt = Quaternion.Inverse(transform.rotation) * seat.rotation;
            if (!hasSwayBaseline)
            {
                swayBaseline = tilt;
                hasSwayBaseline = true;
            }
            else if (deltaTime > 0f)
            {
                swayBaseline = Quaternion.Slerp(swayBaseline, tilt,
                                                1f - Mathf.Exp(-deltaTime / swayBaselineSeconds));
            }

            Quaternion rock = Quaternion.Slerp(Quaternion.identity, tilt * Quaternion.Inverse(swayBaseline), swayFollow);
            Quaternion worldRock = transform.rotation * rock * Quaternion.Inverse(transform.rotation);

            Vector3 seated = seat.position + transform.up * hipsAboveSeat;
            hips.position = Vector3.Lerp(hips.position, seated, weight);
            hips.rotation = Quaternion.Slerp(Quaternion.identity, worldRock, weight) * hips.rotation;
        }

        /// <summary>
        /// Everything the pose reacts to, measured off the mount's transform frame to frame.
        ///
        /// The transform (the saddle's, when one is on), specifically — not a motor's reported velocity. A legged mount's body
        /// height is written by its locomotion each frame and the bob IS the stride; a velocity
        /// figure has that filtered out of it long before anything else can read it, which leaves
        /// the rider sitting perfectly still on a machine that is visibly bouncing.
        /// </summary>
        private void SampleMountMotion(float deltaTime)
        {
            // The saddle when there is one: a NavMesh creature's root glides level, and the bob of
            // its stride is only in the back the saddle rides.
            Transform seat = Seat;
            Vector3 position = seat != null ? seat.position : transform.position;
            float yaw = transform.eulerAngles.y;

            if (!hasLastSample || deltaTime <= 0f)
            {
                lastMountPosition = position;
                lastMountYaw = yaw;
                hasLastSample = true;
                return;
            }

            Vector3 delta = position - lastMountPosition;
            float vertical = delta.y / deltaTime;
            float forward = Vector3.Dot(delta / deltaTime, transform.forward);
            float turn = Mathf.DeltaAngle(lastMountYaw, yaw) / deltaTime;

            lastMountPosition = position;
            lastMountYaw = yaw;

            // A teleport is not a stride. Drop the whole sample rather than clamping it, so a
            // scene migration doesn't leave the rider leaning at the limit for the smoothing's
            // whole time constant afterwards.
            if (Mathf.Abs(vertical) > motionRejectThreshold ||
                Mathf.Abs(forward) > motionRejectThreshold ||
                Mathf.Abs(turn) > motionRejectThreshold * 10f)
                return;

            float k = 1f - Mathf.Exp(-motionSmooth * deltaTime);
            smoothedVertical = Mathf.Lerp(smoothedVertical, vertical, k);
            smoothedForward = Mathf.Lerp(smoothedForward, forward, k);
            smoothedTurn = Mathf.Lerp(smoothedTurn, turn, k);
        }

        /// <summary>
        /// The back giving with the mount: the measured bounce, speed and turn, split over the spine
        /// and chest so it curves over two joints instead of hinging at one. Parents before
        /// children, so the chest's share lands on the already-leaned spine.
        /// </summary>
        private void ApplyMotion(Vector3 motion)
        {
            Lean(HumanBodyBones.Spine, motion * 0.6f);
            Lean(HumanBodyBones.Chest, motion * 0.4f);
        }

        /// <summary>
        /// Rotate one bone by <paramref name="euler"/> degrees about the RIDER's axes, not the
        /// bone's own, on top of whatever the animator posed this frame.
        ///
        /// A humanoid avatar hands back the real rig transforms, and their local axes are whatever
        /// the artist left them as, so a local Euler offset is right on one rig and lopsided on the
        /// next. Conjugating through the rider's rotation makes X "lean forward" and Z "roll right"
        /// on every rig. Multiplicative on the animator's output, so it needs no captured base and
        /// cannot drift.
        /// </summary>
        private void Lean(HumanBodyBones bone, Vector3 euler)
        {
            Transform target = riderAnimator.GetBoneTransform(bone);
            if (target == null)
                return;

            Quaternion riderRotation = riderRoot.rotation;
            Quaternion inRiderFrame = riderRotation * Quaternion.Euler(euler) * Quaternion.Inverse(riderRotation);
            target.rotation = Quaternion.Slerp(Quaternion.identity, inRiderFrame, weight) * target.rotation;
        }
    }
}
